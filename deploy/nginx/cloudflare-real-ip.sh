#!/usr/bin/env bash
# Creates /etc/nginx/snippets/cloudflare-real-ip.conf from the official list
# of Cloudflare addresses. Run on the server as root:
#
#   sudo ./cloudflare-real-ip.sh
#
# Nginx then takes the client address from the CF-Connecting-IP header, but only
# for connections coming from Cloudflare addresses (nobody else can forge it).
set -euo pipefail

OUT=/etc/nginx/snippets/cloudflare-real-ip.conf
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

v4="$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v6)"
[ -n "$v4" ] && [ -n "$v6" ] || { echo "Nie udało się pobrać listy adresów Cloudflare" >&2; exit 1; }

{
  echo "# Cloudflare addresses ($(date -u +%Y-%m-%d)), source: https://www.cloudflare.com/ips/"
  echo "# Generated by cloudflare-real-ip.sh — do not edit by hand."
  for net in $v4 $v6; do
    case "$net" in
      */*) echo "set_real_ip_from $net;" ;;
      *) echo "Nieoczekiwany wpis: $net" >&2; exit 1 ;;
    esac
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

install -d -m 0755 /etc/nginx/snippets
install -m 0644 "$TMP" "$OUT"
echo "Zapisano $OUT ($(grep -c set_real_ip_from "$OUT") zakresów)."
